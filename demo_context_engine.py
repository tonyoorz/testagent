def demo_intent_analysis():
    """演示意图理解"""
    print("\n" + "=" * 70)
    print("演示 1: 意图理解")
    print("=" * 70)
    
    analyzer = IntentAnalyzer()
    
    queries = [
        "最近两周 ABS 模块的测试策略建议",
        "上个月 IDCEVO 项目的缺陷趋势分析",
        "ADC 项目风险最高的模块有哪些",
        "对比 APP 和 BDC 的测试覆盖率",
        "PU:ABC_123 相关的缺陷",
    ]
    
    for query in queries:
        intent = analyzer.analyze(query)
        
        print(f"\n问题: {query}")
        print(f"  ├─ 数据类型: {intent.data_type}")
        print(f"  ├─ 项目: {intent.project or '未指定'}")
        print(f"  ├─ 模块: {intent.module or '未指定'}")
        print(f"  ├─ 时间范围: {intent.time_range}")
        print(f"  ├─ 分析焦点: {intent.focus}")
        print(f"  └─ 置信度: {intent.confidence:.0%}")


def demo_token_estimation():
    """演示 Token 估算"""
    print("\n" + "=" * 70)
    print("演示 2: Token 估算")
    print("=" * 70)
    
    engine = ContextEngine()
    
    texts = [
        ("中文文本", "这是一个简单的测试文本，用于测试中文 Token 估算。"),
        ("英文文本", "This is a simple English text for testing token estimation."),
        ("混合文本", "混合文本 Mixed text with 中英文 Chinese and English。"),
    ]
    
    for name, text in texts:
        tokens = engine._estimate_tokens(text)
        chars = len(text)
        print(f"\n{name}:")
        print(f"  内容: {text[:50]}...")
        print(f"  字符数: {chars}")
        print(f"  估算 Token: {tokens}")
        print(f"  比例: {chars/tokens:.1f} 字符/Token")


